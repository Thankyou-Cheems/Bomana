import { createHash, createPrivateKey, createPublicKey, sign as signMessage } from "node:crypto";
import { readFileSync, writeFileSync } from "node:fs";
import { resolve } from "node:path";

const OFFLINE_PRODUCTION_PUBLIC_KEY = "zSMo0z0dAKYP2j0pV68vJ0NvtonEV1CVyMWz/f5Rd6s=";
const OFFLINE_DEVELOPMENT_SEED = "9463dd868eb1ff5eca58848687c3452afc0844a7d2c1b91e675dcfa2fe5dea99";

export function sharedAircraftParametersName(sha256) {
  return `aircraft-parameters-${sha256.slice(0, 16)}.json`;
}

export function writeOfflineAssetModule(generatedRoot, fileName, exportPrefix, scope, assets, options = {}) {
  const shared = new Set(options.sharedAssetIds ?? []);
  const records = assets.map(([id, kind, asset]) => {
    const path = resolve(generatedRoot, asset);
    const bytes = readFileSync(path);
    const sha256 = createHash("sha256").update(bytes).digest("hex");
    return { id, kind, asset, sha256, size_bytes: bytes.length };
  });
  records.sort((left, right) => left.id.localeCompare(right.id));
  const revisionCore = { schema_version: 1, scope, objects: records.map(({ asset: _asset, ...record }) => record) };
  const root = { ...revisionCore, revision: createHash("sha256").update(canonicalJson(revisionCore)).digest("hex") };
  const signing = offlineSigningContext();
  const signature = signMessage(null, Buffer.from(canonicalJson(root)), signing.privateKey).toString("base64");
  const signedRoot = { ...root, manifest_signature: { algorithm: "ed25519", key_id: signing.keyId, signature } };
  const urls = records.map((record) => {
    const expression = shared.has(record.id)
      ? `sharedAircraftParametersURL(${JSON.stringify(sharedAircraftParametersName(record.sha256))})`
      : `new URL(${JSON.stringify(`./${record.asset}`)}, import.meta.url)`;
    return `  ${JSON.stringify(record.id)}: ${expression},`;
  });
  // Dev fetches the source JSON beside this module. Production web uses one shared
  // URL, and desktop production uses the content-named file copied next to the bundle.
  // A relative dynamic new URL(import.meta.url) is a Vite directory glob.
  const helper = shared.size
    ? `
function sharedAircraftParametersURL(name: string): URL {
  const path = globalThis.location?.pathname ?? "";
  if (!import.meta.env.DEV && (path.startsWith("/app/") || path.startsWith("/mobile/"))) return new URL(\`/app/shared/\${name}\`, globalThis.location.origin);
  const moduleURL = new URL(import.meta.url);
  moduleURL.pathname = moduleURL.pathname.replace(/[^/]*$/, import.meta.env.DEV ? "aircraft-parameters.json" : name);
  return moduleURL;
}
`
    : "";
  writeFileSync(
    resolve(generatedRoot, fileName),
    `// Generated by the shared offline asset builder.\nexport const ${exportPrefix}_OFFLINE_ROOT = Object.freeze(${JSON.stringify(signedRoot)});\nexport const ${exportPrefix}_OFFLINE_URLS = Object.freeze({\n${urls.join("\n")}\n});\n${helper}`,
    "utf8",
  );
}

function offlineSigningContext() {
  const configured = String(process.env.BOMANA_OFFLINE_ROOT_ED25519_PRIVATE_KEY || "").trim();
  if (!configured && process.env.BOMANA_OFFLINE_ROOT_REQUIRE_PRODUCTION === "1") {
    throw new Error("production Browser build requires the Offline Root private key");
  }
  const seed = configured ? decodeSeed(configured) : Buffer.from(OFFLINE_DEVELOPMENT_SEED, "hex");
  const privateKey = createPrivateKey({
    key: Buffer.concat([Buffer.from("302e020100300506032b657004220420", "hex"), seed]),
    format: "der",
    type: "pkcs8",
  });
  const spki = createPublicKey(privateKey).export({ format: "der", type: "spki" });
  const publicKey = spki.subarray(spki.length - 32).toString("base64");
  if (!configured) return { keyId: "bomana-development-only", privateKey };
  const declaredPublic = String(process.env.BOMANA_OFFLINE_ROOT_ED25519_PUBLIC_KEY || "").trim();
  if (declaredPublic !== OFFLINE_PRODUCTION_PUBLIC_KEY || publicKey !== OFFLINE_PRODUCTION_PUBLIC_KEY) {
    throw new Error("configured Offline Root key does not match the pinned production public key");
  }
  return {
    keyId: String(process.env.BOMANA_OFFLINE_ROOT_SIGNING_KEY_ID || "bomana-offline-2026-v1").trim(),
    privateKey,
  };
}

function decodeSeed(value) {
  const seed = /^[0-9a-fA-F]{64}$/.test(value) ? Buffer.from(value, "hex") : Buffer.from(value, "base64");
  if (seed.length !== 32) throw new Error("Offline Root private key must be a 32-byte seed");
  return seed;
}

function canonicalJson(value) {
  if (Array.isArray(value)) return `[${value.map(canonicalJson).join(",")}]`;
  if (value && typeof value === "object") {
    return `{${Object.entries(value).sort(([left], [right]) => left < right ? -1 : left > right ? 1 : 0).map(([key, item]) => `${JSON.stringify(key)}:${canonicalJson(item)}`).join(",")}}`;
  }
  return JSON.stringify(value);
}
